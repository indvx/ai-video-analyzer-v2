from pydantic import BaseModel, Field
from typing import Optional, List
from datetime import datetime


class VideoBase(BaseModel):
    """Core video details returned to the frontend.
    
    Includes database attributes as well as computed properties like `duration` (in seconds)
    and `duration_formatted` (mm:ss) derived from inspecting the video file on disk.
    """
    id: int
    video_name: str
    category: Optional[str] = None
    suitability: Optional[str] = None
    video_type: Optional[str] = None
    duration: Optional[int] = 0
    duration_formatted: Optional[str] = "0:00"
    created_at: Optional[datetime] = None

    class Config:
        # Allows Pydantic to read ORM attributes directly from SQLAlchemy models
        from_attributes = True


class VideoCreate(BaseModel):
    """Payload used when recording a newly uploaded video in the database."""
    video_name: str
    video_type: Optional[str] = "mp4"


class VideoListResponse(BaseModel):
    """Paginated list envelope returned by the `/api/video/list` endpoint."""
    total: int
    videos: List[VideoBase]
    page: int
    limit: int


class SummaryRequest(BaseModel):
    """Parameters for generating a video summary.
    
    Set `is_new_video=True` only during initial uploads so the summary gets chunked 
    and indexed into ChromaDB. Re-running a summary on an existing video should keep it False.
    """
    video_name: str
    prompt: Optional[str] = ""
    is_new_video: Optional[bool] = False


class CustomPromptRequest(BaseModel):
    """User-selected options from the frontend UI (summary style, length, moderation flags)
    that get assembled into a customized prompt string for the LLM.
    """
    summary_type: Optional[str] = "Short summary"
    summary_duration: Optional[int] = 1
    summary_bullet: Optional[bool] = False
    detect_harmful_words: Optional[bool] = False
    detect_harmful_pictures: Optional[bool] = False
    age: Optional[int] = None
    summary_language: Optional[str] = "English"


class TimeRangeSummaryRequest(BaseModel):
    """Specifies a start and end timestamp (in seconds) to cut a subclip and summarize only that segment."""
    video_name: str
    start_time: int
    end_time: int
    prompt: Optional[str] = ""


class SummaryResponse(BaseModel):
    """Standard response containing the video identifier and the generated AI summary."""
    video_name: str
    summary: str


class QuestionRequest(BaseModel):
    """User question directed at a specific video.
    
    If `thread_id` is omitted, the backend falls back to using `video_name` 
    to preserve conversation history across questions for the same video.
    """
    video_name: str
    question: str
    thread_id: Optional[str] = None


class QuestionResponse(BaseModel):
    """Answer generated by the LangGraph RAG pipeline alongside the active thread ID."""
    question: str
    answer: str
    thread_id: str
